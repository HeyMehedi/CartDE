export type Lang = "en" | "bn";
export const LANGS: Record<Lang, Record<MessageKey, string>> = { en, bn };

export const langFor = (locale: string): Lang => (/^bn(\b|[-_])/i.test(locale) ? "bn" : "en");

export function t(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
	const template = LANGS[lang][key] ?? en[key];
	return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Subset of messages for the browser scripts, as a plain object. */
export function clientMessages(lang: Lang, keys: readonly MessageKey[]): Record<string, string> {
	return Object.fromEntries(keys.map((k) => [k, LANGS[lang][k] ?? en[k]]));
}
